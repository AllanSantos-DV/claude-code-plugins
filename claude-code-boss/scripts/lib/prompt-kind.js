'use strict';
/**
 * lib/prompt-kind.js — tell a prompt the USER typed from one the harness made up.
 *
 * Claude Code delivers background-agent results as a UserPromptSubmit whose
 * prompt is a `<task-notification>…</task-notification>` block. The prompt
 * detectors treated it as the user talking: "the user may be correcting you",
 * research_query({query:"<task-notification>"}), and a KB recall over the agent's
 * report — noise injected once per finished background agent.
 */

const SYNTHETIC_PREFIXES = ['<task-notification>'];

/** @param {string} prompt @returns {boolean} true when the harness, not the user, wrote it */
function isSyntheticPrompt(prompt) {
  const p = String(prompt || '').trimStart();
  return SYNTHETIC_PREFIXES.some(prefix => p.startsWith(prefix));
}

// Turns a lesson must not be learned from: what the orchestrator and its services push into a session
// (a delegation, a PEDIDO, the service notices) and what the whatsapp-bridge delivers. They carry
// instructions and the owner's relayed chat, not a correction this session received — captured as
// lessons they only pollute recall. Formats read from real transcripts (the orchestrator window and its
// worker sessions); the same text arrives as a `user` line when the session is idle and as a
// `queued_command` attachment when it is busy. Matched at the head of the turn.
const NON_LESSON_HEAD_CHARS = 600;
const NON_LESSON_PATTERNS = [
  // orchestrator → worker: <cross-session-message from="uds:…" from-name="Jarvis-orquestrador" …>. A peer worker's message is NOT matched.
  /<cross-session-message\b[^>]*\bfrom-name="[^"]*(?:orquestrador|orchestrator|jarvis)/i,
  // the owner's request relayed by the service: PEDIDO 559 (tipo: …
  /^\s*PEDIDO \d+ \(tipo:/,
  // service notices: EVENTO DE SESSÕES (data generated by the service…), COBRANÇA DE … (service, no AI…), PEDIDOS SEM RESPOSTA (service, no AI…)
  /^\s*[A-ZÀ-Ý][A-ZÀ-Ý ]{4,}\((?:service, no AI|data generated by the service)/,
  // whatsapp-bridge deliveries: [Mensagem do dono pelo WhatsApp, entregue pelo whatsapp-bridge], [Mensagens de chats assinados … entregues pelo whatsapp-bridge], [Resultado de proposta … entregue pelo whatsapp-bridge]
  /^\s*\[[^\]\n]{0,200}entregues? pelo whatsapp-bridge/i,
  // a Claude Code channel envelope from WhatsApp
  /<channel\b[^>]*\bsource="[^"]*whatsapp/i,
];

/** @param {string} text a user turn @returns {boolean} true when it is an orchestrator turn or a WhatsApp mirror/channel envelope */
function isOrchestratorOrMirrorTurn(text) {
  const head = String(text || '').slice(0, NON_LESSON_HEAD_CHARS);
  return NON_LESSON_PATTERNS.some(re => re.test(head));
}

module.exports = { isSyntheticPrompt, SYNTHETIC_PREFIXES, isOrchestratorOrMirrorTurn };
